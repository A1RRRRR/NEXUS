export const getDrinkById = (id) => drinks.find((d) => d.id === Number(id))

export const getDrinksByCategory = (category) =>
  category === 'all' ? drinks : drinks.filter((d) => d.category === category)

export const getRelatedDrinks = (drink, count = 3) =>
  drinks
    .filter((d) => d.id !== drink.id && (d.category === drink.category || d.alcoholic === drink.alcoholic))
    .slice(0, count)
